CREATE TABLE reminder_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(200) NOT NULL,
    task_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    channel VARCHAR(16) NOT NULL,
    kind VARCHAR(16) NOT NULL,
    hours_before INT NOT NULL,
    deadline TIMESTAMP(6) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    status VARCHAR(16) NOT NULL,
    attempts INT NOT NULL,
    available_at TIMESTAMP(6) NOT NULL,
    claimed_at TIMESTAMP(6),
    sent_at TIMESTAMP(6),
    last_error VARCHAR(500),
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_reminder_outbox_key UNIQUE (idempotency_key),
    CONSTRAINT fk_reminder_outbox_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
    CONSTRAINT fk_reminder_outbox_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT reminder_outbox_channel CHECK (channel IN ('DISCORD', 'TELEGRAM')),
    CONSTRAINT reminder_outbox_kind CHECK (kind IN ('AT_DEADLINE', 'HOURS_BEFORE')),
    CONSTRAINT reminder_outbox_status CHECK (status IN ('PENDING', 'SENDING', 'SENT', 'DEAD', 'CANCELLED')),
    CONSTRAINT reminder_outbox_attempts CHECK (attempts >= 0)
);

CREATE INDEX idx_reminder_outbox_task ON reminder_outbox (task_id);
CREATE INDEX idx_reminder_outbox_user ON reminder_outbox (user_id);

CREATE INDEX idx_reminder_outbox_pending
    ON reminder_outbox (available_at, id)
    WHERE status = 'PENDING';

CREATE INDEX idx_reminder_outbox_sending
    ON reminder_outbox (claimed_at)
    WHERE status = 'SENDING';
