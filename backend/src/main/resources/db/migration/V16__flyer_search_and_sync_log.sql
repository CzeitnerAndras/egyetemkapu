CREATE EXTENSION IF NOT EXISTS pg_trgm;

ALTER TABLE flyer_products ADD COLUMN name_folded VARCHAR(500);

UPDATE flyer_products
SET name_folded = left(btrim(regexp_replace(
        translate(lower(name), 'áéíóöőúüű', 'aeiooouuu'),
        '[[:space:]]+', ' ', 'g')), 500);

UPDATE flyer_products SET name_folded = '' WHERE name_folded IS NULL;

ALTER TABLE flyer_products ALTER COLUMN name_folded SET NOT NULL;

CREATE INDEX idx_flyer_products_name_folded_trgm
    ON flyer_products USING gin (name_folded gin_trgm_ops);

CREATE TABLE flyer_sync_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store VARCHAR(32) NOT NULL,
    started_at TIMESTAMP(6) NOT NULL,
    finished_at TIMESTAMP(6) NOT NULL,
    status VARCHAR(16) NOT NULL,
    product_count INT NOT NULL,
    error_message VARCHAR(1000),
    CONSTRAINT flyer_sync_runs_status CHECK (status IN ('ok', 'failed'))
);

CREATE INDEX idx_flyer_sync_runs_store_started
    ON flyer_sync_runs (store, started_at DESC);
